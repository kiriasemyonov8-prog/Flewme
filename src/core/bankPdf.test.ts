describe('строки из кусочков PDF', () => {
  it('кусочки на одной высоте — одна строка, слева направо', () => {
    const items: PdfItem[] = [
      { page: 1, x: 300, y: 700, str: '829,96' },
      { page: 1, x: 40, y: 700.8, str: '23.10.2026' },
      { page: 1, x: 100, y: 700, str: '13:49' },
      { page: 1, x: 40, y: 688, str: '23.10.2026 946112' },
    ];
    expect(pdfLines(items)).toEqual(['23.10.2026 13:49 829,96', '23.10.2026 946112']);
  });
});

describe('выписка Сбера', () => {
  const s = parseBankPdf(SBER);
  if (s === 'unknownFormat') throw new Error('не прочитано');

  it('операции: траты без знака — списания, «+» — пополнения', () => {
    expect(s.bank).toBe('sber');
    expect(s.ops.map((o) => [o.date, o.time, o.amount, o.bankCategory])).toEqual([
      ['2026-10-25', '08:19', -280000, 'Прочие операции'],
      ['2026-10-23', '13:49', -82996, 'Оплата по QR–коду СБП'],
      ['2026-10-19', '03:44', -19900, 'Прочие операции'],
      ['2026-10-15', '13:15', 500000, 'Внесение наличных'],
    ]);
  });

  it('описание собирается из двух строк, шапки страниц не мешают', () => {
    expect(s.ops[1].description).toBe('SBSCR_Магнит Супермаркет Омни. Операция по карте ****0000');
    expect(merchantKey(s.ops[1].description)).toBe('МАГНИТ СУПЕРМАРКЕТ');
  });

  it('остаток на конец выписки', () => {
    expect(s.closing).toEqual({ date: '2026-10-25', amount: 180000 });
  });

  it('перевод в ВТБ — не трата, подписка — трата, внесение наличных — пополнение', () => {
    expect(s.ops.map(classifyOp)).toEqual(['transferOut', 'purchase', 'purchase', 'inflow']);
  });
});

describe('справка Т-Банка', () => {
  const s = parseBankPdf(TBANK);
  if (s === 'unknownFormat') throw new Error('не прочитано');

  it('операции с временем и описанием в несколько строк', () => {
    expect(s.bank).toBe('tbank');
    expect(s.ops).toEqual([
      { date: '2026-10-24', time: '20:07', amount: -72918, description: 'Оплата в MAGNOLIYA MOSCOW RUS' },
      { date: '2026-10-17', time: '20:16', amount: -200000, description: 'Внешний перевод по номеру телефона +79990001122' },
      { date: '2026-10-07', time: '22:59', amount: -9900, description: 'Плата за оповещения об операциях' },
    ]);
    expect(s.closing).toBeUndefined();
  });

  it('плата за оповещения — не трата', () => {
    expect(classifyOp(s.ops[2])).toBe('service');
  });
});

describe('незнакомый документ', () => {
  it('понятная ошибка', () => {
    expect(parseBankPdf(['Договор аренды', 'Арендатор обязуется'])).toBe('unknownFormat');
  });
});
